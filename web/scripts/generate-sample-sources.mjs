import {readFile,writeFile} from 'node:fs/promises';
import {resolve} from 'node:path';
const root=resolve(import.meta.dirname,'../..');
const definitions=[
 ['viewer','report-viewer-demo.component.ts',['drillthrough/InvoiceDetails.rdl']],
 ['report-tabs','report-tabs-demo.component.ts',['drillthrough/Invoices.rdl','drillthrough/InvoiceDetails.rdl','drillthrough/CustomerSummary.rdl']],
 ['report-builder','report-builder-demo.component.ts',['docs/SymbolOptions.rdl','docs/GuideDemo.rdl','docs/GuideDetails.rdl']],
];
const files={},examples={};
async function add(path,kind,report){
 if(!files[path])files[path]={path,kind,content:await readFile(resolve(root,path),'utf8')};
 return {path,kind,...(report?{report}:{})};
}
for(const [route,component,reports] of definitions){
 const entries=[await add('web/src/app/reports/'+component,'Angular'),
  await add('web/src/app/app.config.ts','Angular'),await add('web/src/app/report-api.config.ts','Angular'),
  await add('web/public/app.config.json','Configuration'),await add('api/Program.cs','Configuration'),
  await add('api/appsettings.json','Configuration'),await add('api/report-query-map.json','Configuration')];
 if(route==='report-builder'){
  entries.push(await add('web/src/app/reports/currency-options.ts','Angular'));
  entries.push(await add('web/src/app/reports/invoice-action-form.component.ts','Angular'));
 }else entries.push(await add('api/Data/textbox_actions_demo.json','JSON'));
 for(const report of reports)entries.push(await add('api/Reports/'+report,'RDL',report));
 examples['/reports/'+route]=entries;
}
await writeFile(resolve(root,'web/src/app/reports/sample-sources.generated.ts'),
 '// Generated by npm run sources. Do not edit.\nexport default JSON.parse('+JSON.stringify(JSON.stringify({examples,files}))+') as unknown;\n');
console.log(`Prepared source for ${definitions.length} focused examples (${Object.keys(files).length} files).`);
